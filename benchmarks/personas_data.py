def A(day, text, tags, level="fact", w=1.8, ar=0.3, va=0.0, uid="u0", scope=None):
    """构造一条锚点记忆；u0 默认私聊可见，其他 uid 默认 shadow。"""
    if scope is None:
        scope = "private" if uid == "u0" else "shadow"
    return {"day": day, "text": text, "tags": tags.split(), "level": level,
            "w": w, "ar": ar, "va": va, "uid": uid, "scope": scope}


def D(day, uid, text, tags, w=0.45):
    """构造一条群聊干扰，scope 固定 shared，权重低于主人锚点。"""
    return {"day": day, "uid": uid, "text": text, "tags": tags.split(),
            "level": "detail", "w": w, "ar": 0.2, "va": 0.0, "scope": "shared"}


def Q(q, expect, cat, leak=()):
    """构造一道黄金题；boundary 题额外给 leak（出现即算越界）。"""
    return {"q": q, "expect_any": list(expect), "category": cat, "leak": list(leak)}


